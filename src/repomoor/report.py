"""Report rendering: profile JSON, PROJECT_CONTEXT.md, recommendations.md, optional rule files.

Builds file contents only; writing is done by fs.safe_create.
"""
from __future__ import annotations

import json
from pathlib import Path
from typing import Any

from .constants import OUTPUT_DIR, VERSION
from .fs import local_exists

CONTEXT_PATH = f"{OUTPUT_DIR}/PROJECT_CONTEXT.md"

def context_markdown(scan: dict[str, Any], signals: dict[str, Any], answers: dict[str, str]) -> str:
    languages = ", ".join(f"{lang} ({n} files)" for lang, n in list(scan["source_counts"].items())[:8]) or "Not determined yet"
    manifests = ", ".join(f"`{m}`" for m in scan["manifests"][:20]) or "None found"
    note = (f"The scan was truncated ({', '.join(scan.get('truncation_reasons') or ['max_files'])}); counts are lower bounds."
            if scan["scan_truncated"] else "Counts are based on filename scanning, not static analysis.")
    issues = signals.get("parse_issues") or []
    rules = [x["path"] for x in signals.get("instruction_files", [])]
    rules_line = ("\n- Existing agent instructions (these take precedence): " + ", ".join(f"`{p}`" for p in rules[:20]) + (f" and {len(rules) - 20} more" if len(rules) > 20 else "")) if rules else ""
    issue_line = ("\n- Skipped or unparsable files (signals from them are missing): " + ", ".join(f"`{x['path']}` ({x['code']})" for x in issues)) if issues else ""
    return f"""# RepoMoor Project Orientation (generated, review before relying on it)

> These are observed hints, not verified architecture facts. Existing project guidance takes precedence.

- Languages seen: {languages}
- Workspace manifest detected: {"yes" if signals["workspace_detected"] else "no"}
- Possible multiple services/packages: {"yes" if signals["possible_multiservice"] else "not confirmed"}
- Source files sampled: {scan["sampled_source_files"]}; {note}{issue_line}{rules_line}
- Relevant manifests: {manifests}
- Coding agents selected: {answers["agents"]}

## Efficient and reliable exploration

1. Begin with the smallest relevant part of the project; use scoped searches and targeted symbol/file reads.
2. Read existing `AGENTS.md`, `CLAUDE.md`, scoped rules and architecture docs before inventing conventions.
3. Use an already-configured graph only if its index is fresh; verify findings against source and tests.
4. For cross-service or high-risk changes, trace callers, dynamic registrations, configuration and tests; avoid relying on graph completeness.
5. Keep full diagnostics available if compact command output obscures an error.
6. After a verified change, record non-obvious architectural decisions in the team's existing decision-documentation system.

This file does not automatically activate in your AI agent unless you explicitly link it from agent instructions.
"""


def evidence_text(item: dict[str, Any]) -> str:
    return f"`{item['code']}` ← " + "; ".join(f"`{e}`" for e in item["evidence"])


def rec_markdown(plan: dict[str, Any]) -> str:
    why = "; ".join(f"`{e}`" for e in plan["complexity_evidence"]) or "no complexity trigger matched"
    lines = ["# AI Development Stack Recommendation", "", "Generated by a non-destructive local scan. No tools have been installed.", "", f"Complexity: **{plan['complexity_assessment']}** ({why})", "", "Each decision lists its reason code and the evidence that triggered it. Codes are explained in RepoMoor's `docs/ARCHITECTURE.md`.", "", "## Recommended foundation / first pilots", ""]
    for x in plan["recommended"]:
        lines.extend([f"### {x['name']}", "", f"{x['purpose']}. {x['reason']}", "", f"Setup: {x['installation']}", "", f"Why: {evidence_text(x)}", ""])
    lines.extend(["## Optional specialist tools", ""])
    for x in plan["optional_pilots"]:
        lines.append(f"- **{x['name']}**: {x['reason']} Why: {evidence_text(x)}")
    if not plan["optional_pilots"]:
        lines.append("- None until baseline measurements justify it.")
    lines.extend(["", "## Intentionally not configured", ""])
    for x in plan["skipped_details"]:
        lines.append(f"- {x['reason']} Why: {evidence_text(x)}")
    lines.extend(["", "## A/B check before keeping a new integration", ""])
    for x in plan["measurement"]:
        lines.append(f"- {x}")
    lines.extend(["", "Use clean task baselines and confirm the coding agent actually invokes the candidate tools. Do not interpret an individual retrieval's token savings as total task savings.", ""])
    return "\n".join(lines)


def artifact_candidates(root: Path, scan: dict[str, Any], signals: dict[str, Any], answers: dict[str, str], plan: dict[str, Any], integrate: bool) -> tuple[dict[str, str], list[str]]:
    profile = {
        "generator": f"repomoor/{VERSION}",
        "scope": "project-only",
        "no_installation_performed": True,
        "scan": scan,
        "signals": signals,
        "answers": answers,
        "recommendation": plan,
    }
    files: dict[str, str] = {
        f"{OUTPUT_DIR}/project-profile.json": json.dumps(profile, indent=2, ensure_ascii=False) + "\n",
        CONTEXT_PATH: context_markdown(scan, signals, answers),
        f"{OUTPUT_DIR}/recommendations.md": rec_markdown(plan),
    }
    notices: list[str] = []
    if integrate:
        # Be deliberately conservative: if any existing instructions/rules exist, do not
        # add competing rules. Never append, merge, or replace user-owned instructions.
        # Root and nested instruction files both count; see scanner.INSTRUCTION_PATHS.
        existing_rules = [x["path"] for x in signals.get("instruction_files", [])]
        target_taken = [p for p in ("AGENTS.md", "CLAUDE.md") if local_exists(root, p)]  # e.g. symlink or odd case
        if existing_rules or target_taken:
            shown = existing_rules[:10] or target_taken
            more = f" and {len(existing_rules) - 10} more" if len(existing_rules) > 10 else ""
            notices.append("Agent instruction integration skipped: existing project rules were detected (" + ", ".join(shown) + more + "). Manually link " + CONTEXT_PATH + " only if desired.")
        elif scan["scan_truncated"]:
            notices.append("Agent instruction integration skipped: the scan was truncated (" + ", ".join(scan.get("truncation_reasons") or ["max_files"]) + "), so nested project rules cannot be ruled out. Raise the limits or link " + CONTEXT_PATH + " manually.")
        else:
            if answers["agents"] in ("cursor", "both", "other"):
                files["AGENTS.md"] = "# Project agent orientation\n\nFor project-discovery hints and efficient code navigation, consult `" + CONTEXT_PATH + "` as needed. Verify all inferred facts against source.\n"
            if answers["agents"] == "claude":
                files["CLAUDE.md"] = "# Project agent orientation\n\nWhen beginning unfamiliar work, consult `" + CONTEXT_PATH + "` for a brief initial map. Follow source code and tests over inferred metadata.\n"
    return files, notices
